#!/usr/bin/env python3
"""Generates packages/sport_<name>/ — one tiny Flutter package per sport.

Why they exist: tactics_board is both the shared library and the hub app, and
Flutter bundles every asset a dependency declares. So anything the hub needed
(all fifteen drill libraries, all fifteen balls, every sport's equipment) was
bundled into all sixteen apps. A soccer app shipped 13MB of other sports'
drills, a basketball hoop and a set of swim caps.

A sport's assets now live in a package of their own. A shell depends on the
one it is; the hub depends on all fifteen, which is what a hub is.

The files themselves are NOT copied: each entry is a symlink back to the one
copy in tactics_board/assets/, so nothing is duplicated in git and
gen_drills.py keeps writing to exactly one place. Flutter follows them and
bundles the real bytes — verified on a built .app.

    flutter test tool/sport_assets.dart   # in tactics_board/, refreshes the manifest
    python3 tools/gen_sport_packages.py
"""
import json
import os
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
CORE = REPO / "tactics_board"
MANIFEST = REPO / "tools" / "sport_assets.json"
OUT = REPO / "packages"

PUBSPEC = """\
name: {pkg}
description: >-
  {sport}'s own assets: its drill library, its ball and the artwork no other
  sport can show. Generated by tools/gen_sport_packages.py — edit that, or
  the SportType getters it reads, never this file.
publish_to: none
version: 1.0.0

environment:
  sdk: {sdk}

dependencies:
  flutter:
    sdk: flutter

flutter:
  assets:
{assets}"""


def sdk_constraint() -> str:
    for line in (CORE / "pubspec.yaml").read_text().splitlines():
        if line.strip().startswith("sdk:") and "^" in line:
            return line.split("sdk:", 1)[1].strip()
    return "^3.5.0"


def main() -> None:
    data = json.loads(MANIFEST.read_text())
    sdk = sdk_constraint()
    for sport, files in sorted(data.items()):
        pkg = f"sport_{sport.lower()}"
        root = OUT / pkg
        (root / "assets").exists() and _clear(root / "assets")
        for rel in files:
            src = CORE / rel
            if not src.exists():
                raise SystemExit(f"{sport}: {rel} is not in the core")
            dst = root / rel
            dst.parent.mkdir(parents=True, exist_ok=True)
            # ../ back to the repo root, then down into the core.
            up = os.path.relpath(src, dst.parent)
            if dst.is_symlink() or dst.exists():
                dst.unlink()
            dst.symlink_to(up)
        (root / "pubspec.yaml").write_text(PUBSPEC.format(
            pkg=pkg, sport=sport, sdk=sdk,
            assets="".join(f"    - {f}\n" for f in files)))
        print(f"{pkg:24s} {len(files)} assets")


def _clear(d: Path) -> None:
    for p in sorted(d.rglob("*"), reverse=True):
        if p.is_symlink() or p.is_file():
            p.unlink()
        elif p.is_dir():
            p.rmdir()


if __name__ == "__main__":
    main()
